import os
import asyncio, json
from harness import *
results=[]
def check(name, ok, info=""):
    results.append((name, ok)); print(("PASS " if ok else "FAIL ")+name+("" if ok else "  "+str(info)))
def has(log, method, frag): return any(m==method and frag in u for m,u in log)
async def main():
  async with async_playwright() as p:
    b=await p.chromium.launch(executable_path=os.environ.get("CHROME", "/usr/bin/google-chrome"),args=["--no-sandbox"])
    # ---------- phone ----------
    ctx,pg,log,errs=await page(b,390,844,settings={"limit":20,"theme":"light"})
    check("settings preserved (limit 20)", await pg.evaluate("JSON.parse(localStorage.getItem('sr.settings')).limit")==20)
    check("tokens/client id preserved, app shown", await pg.is_visible("#app") and not await pg.is_visible("#setup"))
    check("device indicator live", await pg.get_attribute("html","data-dev")=="live")
    check("mini hidden while hero visible", "hero-in" in (await pg.get_attribute("body","class") or ""))
    log.clear(); await pg.click(".hero .js-play"); await pg.wait_for_timeout(300)
    check("hero play/pause -> PUT pause", has(log,"PUT","/me/player/pause"), log)
    check("optimistic paused state", await pg.get_attribute("html","data-playing")=="false")
    log.clear(); await pg.click(".hero .js-next"); await pg.wait_for_timeout(300); check("hero next", has(log,"POST","/me/player/next"), log)
    log.clear(); await pg.click(".hero .js-prev"); await pg.wait_for_timeout(300); check("hero prev", has(log,"POST","/me/player/previous"), log)
    # tiles
    await pg.wait_for_timeout(600)
    log.clear(); await pg.click("#homeRecent .tile >> nth=1 >> .tmain"); await pg.wait_for_timeout(300)
    check("tile tap plays track", has(log,"PUT","/me/player/play"), log)
    await pg.click("#homeQueue .tile >> nth=0 >> .tmore"); await pg.wait_for_timeout(300)
    check("tile more opens actions", await pg.is_visible("#actions"))
    log.clear(); await pg.click("#actList .actbtn >> text=Add to queue"); await pg.wait_for_timeout(300)
    check("action: add to queue", has(log,"POST","/me/player/queue?uri="), log)
    await pg.click("#homeQueue .tile >> nth=0 >> .tmore"); log.clear(); await pg.click("#actList .actbtn >> text=Save to Liked Songs"); await pg.wait_for_timeout(300)
    check("action: save -> PUT /me/library", has(log,"PUT","/me/library?uris="), log)
    await pg.click("#homeArtists .tile >> nth=0 >> .tmain"); await pg.wait_for_timeout(700)
    check("artist tile -> Discover + artist search", await pg.is_visible("#v-discover") and any('artist%3A' in u for m,u in log), log[-3:])
    # back home, scroll, mini
    await pg.click('#navItems [data-v="home"]'); await pg.evaluate("window.scrollTo(0,900)"); await pg.wait_for_timeout(500)
    check("mini visible after scrolling past hero", "hero-in" not in (await pg.get_attribute("body","class") or ""))
    log.clear(); await pg.click("#mini .js-play"); await pg.wait_for_timeout(300); check("mini play toggles", has(log,"PUT","/me/player/play") or has(log,"PUT","/me/player/pause"), log)
    log.clear(); await pg.click("#mini .js-next"); await pg.wait_for_timeout(300); check("mini next", has(log,"POST","/me/player/next"))
    await pg.click("#miniOpen"); await pg.wait_for_timeout(700)
    check("mini opens expanded player", "open" in (await pg.get_attribute("#np","class")))
    log.clear(); await pg.click("#shuffle"); await pg.wait_for_timeout(300); check("shuffle", has(log,"PUT","/me/player/shuffle?state="), log)
    log.clear(); await pg.click("#repeat"); await pg.wait_for_timeout(300); check("repeat", has(log,"PUT","/me/player/repeat?state=context"), log)
    log.clear(); await pg.click("#np .js-next"); await pg.wait_for_timeout(300); check("np next", has(log,"POST","/me/player/next"))
    log.clear(); await pg.click("#np .js-prev"); await pg.wait_for_timeout(300); check("np prev (track >3s in: restarts like Spotify)", has(log,"PUT","/me/player/seek?position_ms=0"), log)
    log.clear(); await pg.click("#np .js-play"); await pg.wait_for_timeout(300); check("np play/pause", has(log,"PUT","/me/player/p"))
    log.clear(); await pg.evaluate("const s=document.getElementById('seek');s.value=500;s.dispatchEvent(new Event('input'));s.dispatchEvent(new Event('change'))"); await pg.wait_for_timeout(300)
    check("seek", has(log,"PUT","/me/player/seek?position_ms="), log)
    log.clear(); await pg.click("#npSave"); await pg.wait_for_timeout(300); check("heart -> DELETE /me/library (was saved)", has(log,"DELETE","/me/library?uris="), log)
    check("volume hidden for phone, note shown", (not await pg.is_visible("#volume")) and await pg.is_visible("#volNote"))
    await pg.click("#np .js-ambient"); await pg.wait_for_timeout(500)
    check("ambient opens from player", await pg.is_visible("#ambient"))
    log.clear(); await pg.click("#ambient .js-play"); await pg.wait_for_timeout(300); check("ambient play/pause", has(log,"PUT","/me/player/p"))
    await pg.wait_for_timeout(3800); check("ambient controls auto-hide", "calm" in (await pg.get_attribute("#ambient","class")))
    await pg.keyboard.press("Escape"); await pg.wait_for_timeout(300); check("Esc exits ambient", not await pg.is_visible("#ambient"))
    await pg.click("#npClose"); await pg.wait_for_timeout(700); check("close player", "open" not in (await pg.get_attribute("#np","class")))
    # devices
    await pg.click("#deviceBtn"); await pg.wait_for_timeout(600); check("device sheet opens", await pg.is_visible("#devices"))
    log.clear(); await pg.click("#devList .dev >> nth=1"); await pg.wait_for_timeout(400)
    check("transfer to other device", has(log,"PUT","/me/player") and not await pg.is_visible("#devices"), log)
    # insights
    log.clear(); await pg.click('#navItems [data-v="insights"]'); await pg.wait_for_timeout(900)
    check("insights loads top artists+tracks", has(log,"GET","/me/top/artists?time_range=medium_term") and has(log,"GET","/me/top/tracks"))
    log.clear(); await pg.click("#range button >> nth=0"); await pg.wait_for_timeout(600); check("range 4 weeks", has(log,"GET","time_range=short_term"))
    await pg.click("#hourChart .hr >> nth=20"); await pg.wait_for_timeout(300); check("hour bar lists plays", await pg.locator("#hourList .it, #hourList .state").count()>0)
    check("genre card hidden when Spotify returns no genres", not await pg.is_visible("#genreCard"))
    log.clear(); await pg.click("#topTracks .it >> nth=1 >> .itmain"); await pg.wait_for_timeout(300); check("row tap plays", has(log,"PUT","/me/player/play"))
    # discover
    await pg.click('#navItems [data-v="discover"]'); await pg.wait_for_timeout(700)
    log.clear(); await pg.fill("#q","stapleton"); await pg.press("#q","Enter"); await pg.wait_for_timeout(700)
    check("search", has(log,"GET","/search?q=stapleton"), log)
    check("search results render", await pg.locator("#disOut .it").count()>0)
    log.clear(); await pg.click("#genreChips .chip >> nth=0"); await pg.wait_for_timeout(700); check("artist chip search", any('artist%3A' in u for m,u in log))
    # vault
    await pg.click('#navItems [data-v="vault"]'); await pg.wait_for_timeout(900)
    log.clear(); await pg.click("#vaultChips .chip >> text=Oldest saves"); await pg.wait_for_timeout(600); check("vault oldest", has(log,"GET","/me/tracks?limit=40"), log)
    log.clear(); await pg.click("#vaultChips .chip >> text=Surprise me"); await pg.wait_for_timeout(600); check("vault surprise", has(log,"GET","/me/tracks?limit="))
    log.clear(); await pg.click("#vaultChips .chip >> text=2019"); await pg.wait_for_timeout(900); check("vault year", has(log,"GET","/me/tracks?limit=50"))
    # dj
    await pg.click('#navItems [data-v="dj"]'); await pg.wait_for_timeout(500)
    await pg.click("#djMood .chip >> text=Calm"); await pg.click("#djAct .chip >> text=Driving"); await pg.fill("#djLike","Chris Stapleton")
    log.clear(); await pg.click("#djBuild"); await pg.wait_for_timeout(2500)
    check("dj build searches genres + artist", any('genre%3A' in u for m,u in log) and any('artist%3A' in u for m,u in log))
    n=await pg.locator("#djOut .it").count(); check("dj mix renders", n>0, n)
    await pg.click("#djOut .it >> nth=0 >> .more"); await pg.click("#actList .actbtn >> text=Remove from mix"); await pg.wait_for_timeout(300)
    check("dj remove from mix", await pg.locator("#djOut .it").count()==n-1)
    log.clear(); await pg.click("#djSave"); await pg.wait_for_timeout(800)
    check("dj save -> POST /me/playlists + /items", has(log,"POST","/me/playlists") and has(log,"POST","/playlists/pl1/items"), log)
    # settings
    await pg.click("#avatarBtn"); await pg.wait_for_timeout(600); check("avatar opens settings", await pg.is_visible("#v-settings"))
    await pg.click("#themeSeg button >> text=Dark"); check("theme dark", await pg.get_attribute("html","data-theme")=="dark")
    check("theme persisted", await pg.evaluate("JSON.parse(localStorage.getItem('sr.settings')).theme")=="dark")
    await pg.click("#themeSeg button >> text=Light")
    await pg.select_option("#sLimit","30"); check("limit persisted", await pg.evaluate("JSON.parse(localStorage.getItem('sr.settings')).limit")==30)
    await pg.click("#v-settings .setrow.js-devopen"); await pg.wait_for_timeout(400); check("settings device row", await pg.is_visible("#devices"))
    await pg.keyboard.press("Escape"); await pg.wait_for_timeout(200)
    await pg.click("#v-settings .setrow.js-ambient"); await pg.wait_for_timeout(300); check("settings ambient row", await pg.is_visible("#ambient")); await pg.click("#ambClose")
    await pg.click("#signout"); await pg.wait_for_timeout(1000)
    check("sign out -> setup, client id kept", await pg.is_visible("#setup") and await pg.input_value("#clientId")=="0123456789abcdef0123456789abcdef")
    check("phone: no page errors", not [e for e in errs if "frame-ancestors" not in e], errs)
    await ctx.close()
    # ---------- desktop ----------
    ctx,pg,log,errs=await page(b,1280,800,opts={"devtype":"Computer"})
    check("desktop: dock visible, mini+hero hidden", await pg.is_visible("#np") and not await pg.is_visible("#mini") and not await pg.is_visible("#hero"))
    log.clear(); await pg.evaluate("const v=document.getElementById('volume');v.value=30;v.dispatchEvent(new Event('input'))"); await pg.wait_for_timeout(600)
    check("desktop: volume", has(log,"PUT","/me/player/volume?volume_percent=30"), log)
    x0=await pg.evaluate("document.getElementById('homeRecent').scrollLeft")
    await pg.click('.railnav[data-rail="homeRecent"] button >> nth=1'); await pg.wait_for_timeout(700)
    check("desktop: rail arrow scrolls", await pg.evaluate("document.getElementById('homeRecent').scrollLeft")>x0)
    await pg.click('#navItems [data-v="settings"]'); await pg.wait_for_timeout(300); check("desktop: sidebar settings", await pg.is_visible("#v-settings"))
    check("desktop: no horizontal overflow", await pg.evaluate("document.documentElement.scrollWidth")<=1280)
    await ctx.close()
    # ---------- states ----------
    ctx,pg,log,errs=await page(b,390,844,opts={"nodevice":True})
    check("no device: indicator off + connect button", await pg.get_attribute("html","data-dev")=="off" and await pg.is_visible(".hero-connect"))
    await pg.click(".hero-connect"); await pg.wait_for_timeout(400); check("connect opens devices", await pg.is_visible("#devices"))
    check("no device: queue empty state", await pg.locator("#homeQueue .state").count()==1)
    await ctx.close()
    ctx,pg,log,errs=await page(b,390,844,opts={"fail":"/me/top/"})
    await pg.click('#navItems [data-v="insights"]'); await pg.wait_for_timeout(900)
    check("error state with retry", await pg.locator("#topArtists .state.error button").count()==1)
    log.clear(); await pg.click("#topArtists .state.error button"); await pg.wait_for_timeout(500); check("retry refetches", has(log,"GET","/me/top/artists"))
    await ctx.close()
    for w,hh in [(390,844),(844,390),(820,1000),(1280,800)]:
        ctx,pg,log,errs=await page(b,w,hh)
        ow=await pg.evaluate("document.documentElement.scrollWidth"); check(f"{w}x{hh}: no horizontal overflow", ow<=w, ow)
        await ctx.close()
    await b.close()
  print(f"\n{sum(1 for _,o in results if o)}/{len(results)} passed")
asyncio.run(main())
