import os
import asyncio
from harness import *
R=[]
def check(n,ok,info=""): R.append(ok); print(("PASS " if ok else "FAIL ")+n+("" if ok else "  "+str(info)[:300]))
def has(log,m,f): return any(a==m and f in u for a,u in log)
async def main():
  async with async_playwright() as p:
    b=await p.chromium.launch(executable_path=os.environ.get("CHROME", "/usr/bin/google-chrome"),args=["--no-sandbox"])
    ctx,pg,log,errs=await page(b,390,844)
    check("existing settings kept, no reconnect prompt", await pg.is_visible("#app"))
    log.clear(); await pg.click('#navItems [data-v="library"]'); await pg.wait_for_timeout(900)
    check("library loads playlists", has(log,"GET","/me/playlists?limit=50"))
    names=await pg.locator("#libOut .tn").all_inner_texts(); check("liked songs pinned + playlists", names[:2]==["Liked Songs","Deer Stand Mornings"], names)
    await pg.screenshot(path="lib_grid.png")
    await pg.fill("#libFilter","toledo"); await pg.wait_for_timeout(200)
    check("filter", await pg.locator("#libOut .tn").all_inner_texts()==["Toledo Bend Drive"])
    await pg.fill("#libFilter","zzz"); await pg.wait_for_timeout(200); check("filter empty state", await pg.locator("#libOut .state").count()==1)
    await pg.fill("#libFilter","")
    # liked
    log.clear(); await pg.click("#libOut .tile >> nth=0 >> .tmain"); await pg.wait_for_timeout(900)
    check("liked opens detail + /me/tracks", await pg.is_visible("#libDetail") and has(log,"GET","/me/tracks?limit=50&offset=0"))
    check("liked count", (await pg.inner_text("#dSub"))=="812 songs", await pg.inner_text("#dSub"))
    await pg.screenshot(path="lib_liked.png")
    log.clear(); await pg.click("#dPlay"); await pg.wait_for_timeout(300)
    check("play liked context", any(m=="PUT" and "/me/player/play" in u for m,u in log))
    log.clear(); await pg.click("#dShuffle"); await pg.wait_for_timeout(300); check("shuffle liked (shuffle already on in fixture, so only play is sent)", has(log,"PUT","/me/player/play"))
    log.clear(); await pg.click("#dList .it >> nth=0 >> .itmain"); await pg.wait_for_timeout(300); check("row plays in context", has(log,"PUT","/me/player/play"))
    check("load more shown (812 total)", await pg.is_visible("#dMore"))
    log.clear(); await pg.click("#dMore"); await pg.wait_for_timeout(500); check("load more fetches next page", has(log,"GET","/me/tracks?limit=50&offset=2"), log)
    await pg.click("#libBack"); check("back to grid", await pg.is_visible("#libHome"))
    # owned playlist
    log.clear(); await pg.click("#libOut .tile >> nth=1 >> .tmain"); await pg.wait_for_timeout(800)
    check("owned playlist loads /items", has(log,"GET","/playlists/p1/items"))
    check("owned playlist rows", await pg.locator("#dList .it").count()==6)
    await pg.screenshot(path="lib_playlist.png")
    await pg.click("#libBack")
    log.clear(); await pg.click("#libOut .tile >> nth=2 >> .tmain"); await pg.wait_for_timeout(600)
    check("followed playlist: no items call, explains limit, play enabled", not has(log,"GET","/playlists/p2/items") and await pg.locator("#dList .state").count()==1 and not await pg.is_disabled("#dPlay"))
    await pg.screenshot(path="lib_followed.png")
    await pg.click('#navItems [data-v="library"]'); await pg.wait_for_timeout(300); check("tapping Library again closes detail", await pg.is_visible("#libHome"))
    # albums
    log.clear(); await pg.click("#libSeg button >> text=Albums"); await pg.wait_for_timeout(700)
    check("albums load", has(log,"GET","/me/albums?limit=50") and await pg.locator("#libOut .tile").count()==1)
    await pg.click("#libOut .tile >> nth=0 >> .tmain"); await pg.wait_for_timeout(500)
    check("album detail tracks (no extra call)", await pg.locator("#dList .it").count()==3)
    await pg.screenshot(path="lib_album.png")
    await pg.click("#libBack")
    log.clear(); await pg.click("#libSeg button >> text=Artists"); await pg.wait_for_timeout(700)
    check("artists load", has(log,"GET","/me/following?type=artist") and await pg.locator("#libOut .tile").count()==5)
    await pg.screenshot(path="lib_artists.png")
    await pg.click("#libOut .tile >> nth=0 >> .tmain"); await pg.wait_for_timeout(600); check("artist opens songs in Discover", await pg.is_visible("#v-discover"))
    check("no page errors", not [e for e in errs if "frame-ancestors" not in e], errs)
    check("phone: 6 tabs fit, no overflow", await pg.evaluate("document.documentElement.scrollWidth")<=390)
    await ctx.close()
    # error + old scopes
    ctx,pg,log,errs=await page(b,390,844,opts={"fail":"/me/playlists"})
    await pg.click('#navItems [data-v="library"]'); await pg.wait_for_timeout(800)
    check("library error state w/ retry", await pg.locator("#libOut .state.error button").count()==1)
    await ctx.close()
    ctx=await b.new_context(viewport={"width":390,"height":844}); pg=await ctx.new_page()
    await pg.add_init_script("""localStorage.setItem('sr.clientId','0123456789abcdef0123456789abcdef');localStorage.setItem('sr.tokens',JSON.stringify({access:'x',refresh:'y',exp:Date.now()+3e6}));localStorage.setItem('sr.scopes','user-read-playback-state user-modify-playback-state user-read-currently-playing user-read-private user-top-read user-read-recently-played user-library-read user-library-modify playlist-modify-private');""")
    await pg.goto(BASE); await pg.wait_for_timeout(800)
    check("existing install asks once for new permissions, Client ID kept", await pg.is_visible("#setup") and "library" in await pg.inner_text("#setupMsg") and await pg.input_value("#clientId")!="")
    await ctx.close()
    for w,hh,n in [(820,1000,"lib_unfold"),(1280,800,"lib_desktop")]:
        ctx,pg,log,errs=await page(b,w,hh); await pg.click('#navItems [data-v="library"]'); await pg.wait_for_timeout(900)
        await pg.screenshot(path=n+".png"); check(f"{w}: no overflow", await pg.evaluate("document.documentElement.scrollWidth")<=w); await ctx.close()
    await b.close()
  print(f"{sum(R)}/{len(R)} passed")
asyncio.run(main())
